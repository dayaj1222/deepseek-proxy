#!/usr/bin/env python3
"""Generate crates/client/src/device_ids.rs from the Python package.

The DeepSeek login endpoint rejects unknown device ids with
RISK_DEVICE_DETECTED, so the real list must be carried over verbatim.
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO.parent / "deepseek" / ".venv" / "lib" / "python3.12" / "site-packages"))

from aiodeepseek.data.device_ids import DEVICE_IDS  # noqa: E402

TARGET = REPO / "crates" / "client" / "src" / "device_ids.rs"

HEADER = '''//! Device IDs accepted by the DeepSeek iOS login endpoint.
//!
//! Generated by `tools/gen_device_ids.py` from
//! `aiodeepseek/data/device_ids.py`. The server rejects unrecognised values
//! with `RISK_DEVICE_DETECTED`, so these must be real iOS identifiers, not
//! made-up strings.

pub const DEVICE_IDS: [&str; {count}] = [
'''

FOOTER = '''];

/// Pick a device id pseudo-randomly.
pub fn get_device_id() -> &'static str {
    use std::time::{SystemTime, UNIX_EPOCH};
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.subsec_nanos() as usize)
        .unwrap_or(0);
    let pid = std::process::id() as usize;
    DEVICE_IDS[(nanos ^ pid) % DEVICE_IDS.len()]
}
'''


def main() -> int:
    lines = [HEADER.format(count=len(DEVICE_IDS))]
    lines.extend(f'    "{d}",\n' for d in DEVICE_IDS)
    lines.append(FOOTER)
    TARGET.write_text("".join(lines))
    print(f"wrote {len(DEVICE_IDS)} device ids to {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
